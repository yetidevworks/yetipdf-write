<?php

declare(strict_types=1);

// Writes resources/unicode.php, the Unicode data YetiPDF Write needs beyond what PCRE knows:
//   mirror     code point => its mirrored code point (BidiMirroring.txt)
//   brackets   code point => [paired bracket, opening] (BidiBrackets.txt)
//   decompose  code point => canonical decomposition, one level (UnicodeData.txt)
//   compose    "first second" => primary composite (decompositions not excluded from composition)
//   ccc        code point => canonical combining class, non-zero ones only
//   joining    code point => joining type for Arabic-style joining (ArabicShaping.txt), as
//              HarfBuzz numbers them: 0 U, 1 L, 2 R, 3 D (and C), 4 Alaph, 5 Dalath/Rish, 7 T
//
//   php tools/unicode-data.php <dir with those files and DerivedNormalizationProps.txt>
//
// (Bidi classes and general categories come from PCRE's \p{...}, so they need no table.)

$dir = $argv[1] ?? exit("usage: php tools/unicode-data.php <ucd dir>\n");
$rows = function (string $file) use ($dir): array {
    $out = [];
    foreach (file("$dir/$file", FILE_IGNORE_NEW_LINES) as $line) {
        $line = trim(explode('#', $line, 2)[0]);
        if ($line !== '') {
            $out[] = array_map('trim', explode(';', $line));
        }
    }
    return $out;
};
preg_match('/(\d+\.\d+\.\d+)/', (string) file_get_contents("$dir/BidiMirroring.txt", length: 200), $v);

$mirror = [];
foreach ($rows('BidiMirroring.txt') as [$cp, $to]) {
    $mirror[hexdec($cp)] = hexdec($to);
}
$brackets = [];
foreach ($rows('BidiBrackets.txt') as [$cp, $pair, $type]) {
    $brackets[hexdec($cp)] = [hexdec($pair), $type === 'o'];
}
$excluded = [];
foreach ($rows('DerivedNormalizationProps.txt') as $r) {
    if (($r[1] ?? '') === 'Full_Composition_Exclusion') {
        [$a, $b] = array_pad(explode('..', $r[0]), 2, null);
        for ($c = hexdec($a), $e = hexdec($b ?? $a); $c <= $e; $c++) {
            $excluded[$c] = true;
        }
    }
}
$decompose = [];
$compose = [];
$ccc = [];
foreach ($rows('UnicodeData.txt') as $f) {
    $cp = hexdec($f[0]);
    if ((int) $f[3] !== 0) {
        $ccc[$cp] = (int) $f[3];
    }
    if ($f[5] !== '' && $f[5][0] !== '<') {
        $parts = array_map('hexdec', explode(' ', $f[5]));
        $decompose[$cp] = $parts;
        if (count($parts) === 2 && !isset($excluded[$cp])) {
            $compose[$parts[0] . ' ' . $parts[1]] = $cp;
        }
    }
}
$joining = [];
foreach ($rows('ArabicShaping.txt') as [$cp, , $type, $group]) {
    $joining[hexdec($cp)] = match (true) {
        $group === 'ALAPH' => 4,
        $group === 'DALATH RISH' => 5,
        default => ['U' => 0, 'L' => 1, 'R' => 2, 'D' => 3, 'C' => 3, 'T' => 7][$type],
    };
}
foreach ([&$mirror, &$brackets, &$decompose, &$ccc, &$joining] as &$table) {
    ksort($table);
}
unset($table);

$out = ['mirror' => $mirror, 'brackets' => $brackets, 'decompose' => $decompose, 'compose' => $compose, 'ccc' => $ccc, 'joining' => $joining];
$php = "<?php\n\n// Generated by tools/unicode-data.php from Unicode {$v[1]}.\n\nreturn " . preg_replace(["/\n\s*/", '/,\)/', '/array \(/'], ['', ')', '['], var_export($out, true)) . ";\n";
$php = str_replace(')', ']', $php);
file_put_contents(dirname(__DIR__) . '/resources/unicode.php', $php);
printf("%d mirrored, %d brackets, %d decompositions, %d compositions, %d combining classes, %d joining types\n", count($mirror), count($brackets), count($decompose), count($compose), count($ccc), count($joining));
